// Vendor the Tajawal web font locally.
//
// The native app must render instantly and work offline, so it must not depend on
// fonts.googleapis.com at runtime. This script downloads the woff2 files once (at
// build time) and writes a self-hosted stylesheet that index.html loads instead of
// the Google Fonts <link>.
//
// Writes:
//   public/fonts/*.woff2   - font binaries
//   public/fonts/tajawal.css - @font-face rules pointing at the local files
import { writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = resolve(root, 'public/fonts')
mkdirSync(outDir, { recursive: true })

const CSS_URL =
  'https://fonts.googleapis.com/css2?family=Tajawal:wght@300;400;500;700;800;900&display=swap'
// A modern browser UA is required, otherwise Google serves legacy ttf instead of woff2.
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'

const res = await fetch(CSS_URL, { headers: { 'User-Agent': UA } })
if (!res.ok) throw new Error(`google fonts css: ${res.status}`)
let css = await res.text()

const blocks = css.split('@font-face').slice(1)
let out = '/* Self-hosted Tajawal (generated by scripts/vendor-fonts.mjs) - do not edit */\n'
let count = 0

for (const raw of blocks) {
  const block = raw.split('}')[0]
  const weight = (block.match(/font-weight:\s*([0-9]+)/) || [])[1]
  const style = (block.match(/font-style:\s*([a-z]+)/) || [])[1] || 'normal'
  const range = (block.match(/unicode-range:\s*([^;]+);/) || [])[1]
  const url = (block.match(/url\((https:[^)]+)\)/) || [])[1]
  if (!url) continue

  const file = `tajawal-${weight}-${range ? range.split(' ')[0] : 'x'}.woff2`.replace(
    /[^\w.-]/g,
    '_'
  )
  const dest = resolve(outDir, file)

  if (!existsSync(dest)) {
    const bin = await fetch(url, { headers: { 'User-Agent': UA } })
    if (!bin.ok) throw new Error(`font ${url}: ${bin.status}`)
    writeFileSync(dest, Buffer.from(await bin.arrayBuffer()))
  }

  out += `@font-face {\n  font-family: 'Tajawal';\n  font-style: ${style};\n  font-weight: ${weight};\n  font-display: swap;\n`
  if (range) out += `  unicode-range: ${range.trim()};\n`
  out += `  src: url('/fonts/${file}') format('woff2');\n}\n`
  count++
}

writeFileSync(resolve(outDir, 'tajawal.css'), out)
console.log(`fonts: vendored ${count} Tajawal faces into public/fonts`)
