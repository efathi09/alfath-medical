// Generates functions/api/_data/seed.js from the static data modules.
// The API uses it as a DB-less fallback so the whole stack runs locally
// with zero accounts, and stays available if the database is unreachable.
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const { products } = await import(pathToFileURL(resolve(root, 'src/data/products.js')).href)
const { categories } = await import(pathToFileURL(resolve(root, 'src/data/categories.js')).href)
const { company } = await import(pathToFileURL(resolve(root, 'src/data/company.js')).href)
const { heroSlides, flashDeals } = await import(pathToFileURL(resolve(root, 'src/data/promos.js')).href)

const catRows = categories.map((c, i) => ({
  id: c.id,
  slug: c.id,
  name_ar: c.name?.ar ?? null,
  name_en: c.name?.en ?? null,
  desc_ar: c.desc?.ar ?? null,
  desc_en: c.desc?.en ?? null,
  icon: c.icon ?? null,
  art: c.art ?? null,
  tint: c.tint ?? null,
  featured_ar: c.featured?.ar ?? null,
  featured_en: c.featured?.en ?? null,
  groups: c.groups ?? [],
  sort_order: i,
  is_active: true,
}))

const prodRows = products.map((p, i) => ({
  id: p.id,
  sku: p.sku ?? null,
  slug: p.id,
  name_ar: p.name?.ar ?? null,
  name_en: p.name?.en ?? null,
  category_slug: p.category ?? null,
  brand: p.brand ?? null,
  price_egp: p.price ?? 0,
  compare_at_price_egp: p.oldPrice ?? null,
  rating: p.rating ?? 0,
  reviews: p.reviews ?? 0,
  art: p.art ?? null,
  palette: p.palette ?? null,
  unit_ar: p.unit?.ar ?? null,
  unit_en: p.unit?.en ?? null,
  min_order: p.minOrder ?? 1,
  stock: p.stock ?? 0,
  badges: p.badges ?? [],
  keywords: p.keywords ?? [],
  is_active: true,
  sort_order: i,
}))

const settings = {
  phone: company.phone ?? '',
  phoneHref: company.phoneHref ?? '',
  whatsapp: company.whatsapp ?? '',
  email: company.email ?? '',
  address: company.address ?? { ar: '', en: '' },
  workingHours: company.workingHours ?? { ar: '', en: '' },
  vat: company.vat ?? '',
  cr: company.cr ?? '',
  social: company.social ?? [],
  payments: company.payments ?? [],
  trustBadges: company.trustBadges ?? [],
  banners: heroSlides.map((s, i) => ({
    id: s.id,
    href: s.href,
    palette: s.palette,
    art: s.art,
    kicker: s.kicker ?? { ar: '', en: '' },
    stat: s.stat ?? { ar: '', en: '' },
    title: { ar: '', en: '' },
    sub: { ar: '', en: '' },
    cta: { ar: '', en: '' },
    titleKey: s.titleKey,
    subKey: s.subKey,
    ctaKey: s.ctaKey,
    isActive: true,
    sortOrder: i,
  })),
}

const brandRows = (company.brands ?? []).map((name, i) => ({
  id: `b-${i + 1}`,
  name,
  isActive: true,
  sortOrder: i,
}))

const promoRows = (flashDeals ?? []).map((d, i) => ({
  id: d.id,
  dealPrice: d.dealPrice,
  stockTotal: d.stockTotal,
  sold: d.sold,
  isActive: true,
  sortOrder: i,
}))

const outDir = resolve(root, 'functions/api/_data')
mkdirSync(outDir, { recursive: true })

const body =
  '// AUTO-GENERATED by scripts/gen-seed.mjs — do not edit by hand.\n' +
  `// generated_at: ${new Date().toISOString()}\n` +
  `export const SEED = ${JSON.stringify(
    { categories: catRows, products: prodRows, settings, brands: brandRows, promos: promoRows },
    null,
    2,
  )}\n`

writeFileSync(resolve(outDir, 'seed.js'), body, 'utf8')

console.log('wrote functions/api/_data/seed.js')
console.log('  categories:', catRows.length)
console.log('  products  :', prodRows.length)
console.log('  brands    :', brandRows.length)
console.log('  promos    :', promoRows.length)
console.log('  banners   :', settings.banners.length)
