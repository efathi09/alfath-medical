export function adminT(lang) {
  return (key) => {
    const entry = dict[key]
    if (!entry) return key
    return entry[lang] ?? entry.en
  }
}

export function useAdminT() {
  const { lang } = useLang()
  return useMemo(() => adminT(lang), [lang])
}
